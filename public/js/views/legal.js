export function openDoc(key) {
  const doc = DOCS[key];
  if (!doc) return;
  return modal({
    title: doc.title,
    sub: doc.sub,
    wide: true,
    body: h('div', { class: 'doc' },
      doc.blocks.map(([title, items]) => h('section', { class: 'doc__block' },
        h('h4', { class: 'doc__title' }, title),
        h('ul', { class: 'doc__list' },
          items.map((t) => h('li', {}, t)))))),
    actions: [{ label: 'Закрыть', class: 'btn--ghost', value: true }],
  });
}
